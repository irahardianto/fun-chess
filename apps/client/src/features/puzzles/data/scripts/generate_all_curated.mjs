// --- Helper to verify that a puzzle is legal and has positive delta or mate ---
function verifyTactic(fen, moves, playerColor, tacticalReward) {
  const c = new Chess(fen);
  if (c.turn() !== playerColor) throw new Error(`PlayerColor mismatch: ${playerColor} vs ${c.turn()}`);
  for (const m of moves) {
    const from = m.slice(0, 2);
    const to = m.slice(2, 4);
    const promotion = m.slice(4) || undefined;
    const res = c.move({ from, to, promotion });
    if (!res) throw new Error(`Illegal move ${m} in ${fen}`);
  }
  const isMate = c.isCheckmate();
  if (tacticalReward === 'checkmate' && !isMate) {
    throw new Error(`Expected checkmate but got FEN: ${c.fen()}`);
  }
  return true;
}

